"""
compare_datasets.py - build CROSS_DATASET.md from the JSON results.

Usage:
    python compare_datasets.py [results_dir] [output.md]

Part 1 lists columns that are shared BY NAME across datasets (strict).
Part 2 lists columns that mean the same thing under different names. That
mapping (CONCEPTS below) is the analyst's judgement, not something detected
automatically, and it is labeled as such in the output.
Part 3 summarizes the datasets side by side and the benchmark timings.
"""

import glob
import json
import os
import sys

DATASETS = [("fb_ads", "Facebook Ads"), ("fb_posts", "Facebook Posts"), ("tw_posts", "Twitter/X Posts")]
APPROACHES = ["pure_python", "pandas", "polars"]

# concept -> {dataset key: column name}   (analyst-defined equivalence)
CONCEPTS = {
    "Likes": {"fb_posts": "Likes", "tw_posts": "likeCount"},
    "Comments / replies": {"fb_posts": "Comments", "tw_posts": "replyCount"},
    "Shares / retweets": {"fb_posts": "Shares", "tw_posts": "retweetCount"},
    "Views": {"fb_posts": "Total Views", "tw_posts": "viewCount"},
}


def load(d):
    out = {}
    for key, _ in DATASETS:
        for a in APPROACHES:
            p = glob.glob(os.path.join(d, f"*{key}*__{a}.json"))
            if p:
                out.setdefault(key, {})[a] = json.load(open(p[0], encoding="utf-8"))
    return out


def f(v, nd=2):
    if v is None:
        return "-"
    if isinstance(v, float):
        return f"{v:,.{nd}f}"
    return f"{v:,}" if isinstance(v, int) else str(v)


def main():
    d = sys.argv[1] if len(sys.argv) > 1 else "results"
    out_path = sys.argv[2] if len(sys.argv) > 2 else "CROSS_DATASET.md"
    res = load(d)
    base = {k: (v.get("pandas") or next(iter(v.values()))) for k, v in res.items()}
    L = ["# Cross-dataset comparison", "",
         "Generated by `compare_datasets.py` from the JSON results in `results/`. "
         "All numbers are produced by the three scripts (which agree with each other; see `results/verification.txt`).", ""]

    L += ["## 1. The three datasets side by side", "",
          "| | " + " | ".join(n for k, n in DATASETS if k in base) + " |",
          "|---|" + "---|" * len(base)]
    def row(label, fn):
        L.append(f"| {label} | " + " | ".join(fn(base[k]) for k, _ in DATASETS if k in base) + " |")
    row("Rows", lambda r: f(r["n_rows"]))
    row("Columns", lambda r: f(r["n_cols"]))
    for t in ("numeric", "flag", "categorical", "date", "list", "dict", "empty"):
        row(f"Detected {t} columns", lambda r, t=t: f(sum(1 for i in r["columns"].values() if i["type"] == t)))
    for g, label in (("primary", "Auto-chosen group key"), ("primary_plus_id", "Group key + row id"), ("time", "Time key")):
        row(label, lambda r, g=g: ("`" + "`, `".join(r["group_keys"][g]) + "`") if r["group_keys"].get(g) else "-")
    row("Groups in primary grouping", lambda r: f(r["groups"]["primary"]["n_groups"]) if "primary" in r["groups"] else "-")
    L.append("")

    L += ["## 2. Columns shared by name (strict match)", ""]
    names = {k: set(r["columns"]) for k, r in base.items()}
    shared_all = [c for c in base[next(iter(base))]["columns"] if all(c in names[k] for k in names)]
    pair = sorted((names["fb_ads"] & names["tw_posts"]) - names["fb_posts"]) if {"fb_ads", "tw_posts", "fb_posts"} <= set(names) else []
    L += [f"{len(shared_all)} columns appear (by exact name) in all three datasets; "
          f"{len(pair)} more appear in Ads and Twitter only: {', '.join('`'+c+'`' for c in pair)}. "
          "Facebook Ads and Facebook Posts share no columns that Twitter lacks.", "",
          "Rate of each flag (share of rows where the flag is 1/True):", "",
          "| Column | " + " | ".join(n for k, n in DATASETS if k in base) + " | Max gap (pp) |",
          "|---|" + "---|" * (len(base) + 1)]
    gaps = []
    for c in shared_all:
        vals = [base[k]["columns"][c].get("rate") for k, _ in DATASETS if k in base]
        if all(v is not None for v in vals):
            gaps.append((max(vals) - min(vals), c, vals))
    for gap, c, vals in sorted(gaps, reverse=True):
        L.append(f"| `{c}` | " + " | ".join(f"{v*100:.2f}%" for v in vals) + f" | {gap*100:.2f} |")
    other = [c for c in shared_all if c not in [g[1] for g in gaps]]
    if other:
        L += ["", "Shared by name but not a flag in every dataset: " + ", ".join(f"`{c}`" for c in other)]
    for c in pair:
        L += ["", f"`{c}` in Ads / Twitter: " + "; ".join(
            f"{n}: type={base[k]['columns'][c]['type']}" + (f", rate={base[k]['columns'][c]['rate']*100:.2f}%" if base[k]['columns'][c]["type"] == "flag" else f", nunique={base[k]['columns'][c].get('nunique', '-')}")
            for k, n in DATASETS if k in ("fb_ads", "tw_posts") and k in base)]

    L += ["", "## 3. Same idea, different column name (analyst-defined mapping, NOT auto-detected)", "",
          "| Concept | Dataset | Column | Mean | Median | Max | Missing |", "|---|---|---|---|---|---|---|"]
    for concept, m in CONCEPTS.items():
        for k, col in m.items():
            if k in base and col in base[k]["columns"] and base[k]["columns"][col]["type"] == "numeric":
                i = base[k]["columns"][col]
                L.append(f"| {concept} | {dict(DATASETS)[k]} | `{col}` | {f(i['mean'])} | {f(i['median'])} | {f(i['max'], 0)} | {f(i['missing'])} |")
    L += ["", "Caveat: a Facebook 'share' and a retweet, or a Facebook total view and a tweet view count, "
          "are not measured identically by the two platforms, so these rows show the shape of the numbers, not a like-for-like ranking.", ""]

    L += ["## 4. Grouped analysis side by side", "",
          "| Dataset | Grouping | Groups | Smallest | Median | Largest | Rows with a null key |", "|---|---|---|---|---|---|---|"]
    for k, n in DATASETS:
        if k in base:
            for g in ("primary", "time", "primary_plus_id"):
                if g in base[k]["groups"]:
                    G = base[k]["groups"][g]; s = G["size_distribution"]
                    L.append(f"| {n} | `{'`+`'.join(G['keys'])}` | {f(G['n_groups'])} | {f(s['min'])} | {f(s['median'])} | {f(s['max'])} | {f(G['rows_with_null_key'])} |")
    L.append("")

    L += ["## 5. Benchmark: wall-clock seconds per run (includes reading the file)", "",
          "| Dataset | Pure Python | Pandas | Polars |", "|---|---|---|---|"]
    for k, n in DATASETS:
        if k in res:
            L.append(f"| {n} | " + " | ".join(f(res[k][a]["elapsed_seconds"], 3) if a in res[k] else "-" for a in APPROACHES) + " |")
    L.append("")
    open(out_path, "w", encoding="utf-8").write("\n".join(L))
    print(f"wrote {out_path} ({len(L)} lines)")


if __name__ == "__main__":
    main()
